def seg(layer, groups):
    """groups: [(name, desc, keywords列表)] 依序匹配 title+event_time"""
    out = []
    used = set()
    for name, desc, kws in groups:
        ids = []
        for e in fl:
            if e["timeline_layer"] != layer or e["event_id"] in used:
                continue
            hay = (e["title"] + " " + (e.get("event_time") or ""))
            if any(k in hay for k in kws):
                ids.append(e["event_id"])
        if ids:
            out.append({"seg_name": name, "seg_desc": desc, "event_ids": ids})
            used.update(ids)
    # 未匹配
    rest = [e["event_id"] for e in fl if e["timeline_layer"] == layer and e["event_id"] not in used]
    if rest:
        out.append({"seg_name": "其他/补遗", "seg_desc": "本层其余事件", "event_ids": rest})
    return out

