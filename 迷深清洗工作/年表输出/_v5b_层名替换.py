def replace_block(fname, new_block):
    p = os.path.join(BASE, fname)
    s = io.open(p, encoding="utf-8").read()
    import re
    # LAYER_META 定义块: 从 "LAYER_META = {" 到下一个 "}" (在 LAYER_ORDER/AXIS_NAME 等之前)
    m = re.search(r'LAYER_META = \{.*?\n\}', s, flags=re.S)
    if not m:
        print(fname, "未找到 LAYER_META 块"); return
    s2 = s[:m.start()] + new_block + s[m.end():]
    io.open(p, "w", encoding="utf-8").write(s2)
    print(fname, "LAYER_META 已替换")

